"""Command line.

    python -m bpmtools build-models          YAML definitions -> models/*.bpmn
    python -m bpmtools lint models/x.bpmn    check any BPMN 2.0 file
    python -m bpmtools check                 catalog + models -> reports/governance_report.md
                                             exits with 1 if a released process breaks a rule
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

from . import catalog, generate, lint


def md(df: pd.DataFrame) -> str:
    if df.empty:
        return "None."
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def findings_frame(fs) -> pd.DataFrame:
    return pd.DataFrame([f.__dict__ for f in fs], columns=["file", "rule", "severity", "element", "message"])


def cmd_check(root: Path, out: Path) -> int:
    repo = catalog.Repo.load(root)
    gov, models = catalog.check_catalog(repo)
    dash = catalog.dashboard(repo, gov, models)
    heat = catalog.capability_heatmap(repo)
    procs = repo.processes()
    status_by_id = dict(zip(procs["id"], procs["status"]))
    model_status = {m: s for m, s in zip(procs["model"], procs["status"]) if isinstance(m, str)}

    blocking = [f for f in gov if f.severity == "error" and status_by_id.get(f.element.split(" ")[0]) == "released"]
    blocking += [f for f in models if f.severity == "error" and model_status.get(f.file) == "released"]

    inv = pd.DataFrame({p.name: lint.element_inventory(p) for p in sorted(repo.models_dir.glob("*.bpmn"))}).fillna(0).astype(int)
    inv["total"] = inv.sum(axis=1)
    inv = inv.sort_values("total", ascending=False).reset_index().rename(columns={"index": "element"})

    house = procs.groupby(["area_id", "area", "area_type"]).agg(
        processes=("id", "count"), released=("status", lambda s: int((s == "released").sum())), modelled=("model", lambda s: int(s.map(lambda m: isinstance(m, str)).sum()))
    ).reset_index()

    out.mkdir(parents=True, exist_ok=True)
    findings_frame(gov + models).to_csv(out / "findings.csv", index=False)
    heat.to_csv(out / "capability_heatmap.csv", index=False)
    inv.to_csv(out / "migration_inventory.csv", index=False)
    (out / "dashboard.json").write_text(json.dumps(dash, indent=2), encoding="utf-8")

    report = [
        f"# Process governance report: {repo.catalog['company']}",
        "",
        f"As of {repo.catalog['as_of']}. Generated by `python -m bpmtools check`.",
        "",
        "## Dashboard",
        "",
        md(pd.DataFrame([{"measure": k, "value": v} for k, v in dash.items()])),
        "",
        "## Process house",
        "",
        md(house),
        "",
        "## Blocking findings (released processes)",
        "",
        md(findings_frame(blocking)),
        "",
        "## Governance findings",
        "",
        md(findings_frame(gov)[["rule", "severity", "element", "message"]]),
        "",
        "## Model findings",
        "",
        md(findings_frame(models)[["file", "rule", "severity", "element", "message"]]),
        "",
        "## Capability heat map",
        "",
        "Gap = importance minus maturity. High priority: gap of 2 or more, or an important capability with no live process.",
        "",
        md(heat),
        "",
        "## Migration inventory (BPMN elements per model)",
        "",
        md(inv),
        "",
    ]
    (out / "governance_report.md").write_text("\n".join(report), encoding="utf-8")
    print(json.dumps(dash, indent=2))
    print(f"{len(blocking)} blocking finding(s).")
    for f in blocking:
        print(f"  {f.rule} {f.element}: {f.message}")
    return 1 if blocking else 0


def main(argv=None) -> None:
    p = argparse.ArgumentParser(prog="bpmtools")
    p.add_argument("command", choices=["build-models", "lint", "check"])
    p.add_argument("files", nargs="*")
    p.add_argument("--root", default=".")
    p.add_argument("--out", default="reports")
    a = p.parse_args(argv)
    root = Path(a.root)
    if a.command == "build-models":
        for f in generate.build_all(root / "models" / "src", root / "models"):
            print(f"wrote {f}")
    elif a.command == "lint":
        repo = catalog.Repo.load(root)
        fs = lint.lint_paths([Path(f) for f in a.files], repo.verbs, repo.governance["rules"]["max_flow_nodes_per_model"])
        for f in fs:
            print(f"{f.file}: {f.severity} {f.rule} {f.element}: {f.message}")
        sys.exit(1 if any(f.severity == "error" for f in fs) else 0)
    else:
        sys.exit(cmd_check(root, Path(a.out)))


if __name__ == "__main__":
    main()
